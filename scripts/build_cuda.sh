#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
EXACTSAMPLE_PYTHON="${EXACTSAMPLE_PYTHON:-python3}"
EXACTSAMPLE_BUILD="${EXACTSAMPLE_BUILD:-build/cuda}"
EXACTSAMPLE_INSTALL_PREFIX="${EXACTSAMPLE_INSTALL_PREFIX:-$PWD/python}"
EXACTSAMPLE_TORCH_PREFIX="$("$EXACTSAMPLE_PYTHON" -c 'import torch; print(torch.utils.cmake_prefix_path)')"
cmake -S . -B "$EXACTSAMPLE_BUILD" -DCMAKE_BUILD_TYPE=Release \
  -DCMAKE_CUDA_ARCHITECTURES="${EXACTSAMPLE_CUDA_ARCHITECTURES:-89}" \
  -DTORCH_CUDA_ARCH_LIST="${TORCH_CUDA_ARCH_LIST:-8.9}" \
  -DCMAKE_PREFIX_PATH="$EXACTSAMPLE_TORCH_PREFIX"
cmake --build "$EXACTSAMPLE_BUILD" --parallel "${EXACTSAMPLE_BUILD_JOBS:-2}"
cmake --install "$EXACTSAMPLE_BUILD" --prefix "$EXACTSAMPLE_INSTALL_PREFIX"
